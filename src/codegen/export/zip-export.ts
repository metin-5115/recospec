import JSZip from 'jszip'
import type { GeneratedCode } from '@shared/types/generated'
import type { Session } from '@shared/types/session'

const README_TEMPLATE = (session: Session) => `\
# PlayForge — Generated Test

Session: **${session.name}**
Generated: ${new Date().toISOString()}
Start URL: ${session.startUrl}

## How to run

\`\`\`bash
npm install
npx playwright install chromium
npx playwright test
\`\`\`

## Project structure

\`\`\`
pages/       Page Object Model classes (one file per page)
tests/       Test scenarios
playwright.config.ts
package.json
\`\`\`

Generated by [PlayForge](https://github.com/your-username/playforge).
`

/** Classify a generated file into its ZIP folder. */
function resolveZipPath(filename: string): string {
  if (filename.endsWith('.spec.ts')) return `tests/${filename}`
  if (filename === 'package.json') return filename
  if (filename === 'playwright.config.ts') return filename
  if (filename === 'tsconfig.json') return filename
  // All remaining .ts files are page objects
  if (filename.endsWith('.ts')) return `pages/${filename}`
  return filename
}

export async function buildZipExport(session: Session, code: GeneratedCode): Promise<Blob> {
  const zip = new JSZip()

  for (const file of code.files) {
    zip.file(resolveZipPath(file.filename), file.content)
  }

  zip.file('README.md', README_TEMPLATE(session))

  return zip.generateAsync({ type: 'blob', compression: 'DEFLATE' })
}

export async function downloadZipExport(session: Session, code: GeneratedCode): Promise<void> {
  const blob = await buildZipExport(session, code)
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${slugify(session.name)}_${session.sessionId.slice(0, 8)}.zip`
  a.click()
  URL.revokeObjectURL(url)
}

function slugify(name: string): string {
  return name.replace(/\s+/g, '_').replace(/[^\w-]/g, '')
}
