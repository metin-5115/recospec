import JSZip from 'jszip'
import type { GeneratedCode } from '@shared/types/generated'
import type { Session } from '@shared/types/session'

const README_TEMPLATE = (session: Session, framework: string) => {
  const isCypress = framework === 'cypress'
  const runCommand = isCypress
    ? '```bash\nnpm install\nnpx cypress run\n```'
    : '```bash\nnpm install\nnpx playwright install chromium\nnpx playwright test\n```'
  const structure = isCypress
    ? '```\ncypress/e2e/        Test scenarios\ncypress/pages/      Page Object Model classes\ncypress/support/    Custom commands (incl. cy.selfHealing)\ncypress.config.js\npackage.json\n```'
    : '```\npages/       Page Object Model classes (one file per page)\ntests/       Test scenarios\nutils/       selfHealingLocator helper\nplaywright.config.ts\npackage.json\n```'

  const selfHealingNote = isCypress
    ? '`cypress/support/locator.js` registers `cy.selfHealing([...])` — pass the primary selector and recorded fallbacks; the first one that matches wins.'
    : '`utils/locator.ts` exports `selfHealingLocator(page, [...])` — pass the primary selector and recorded fallbacks; the first one whose `count()` is positive wins.'

  return `\
# PlayForge — Generated Test

Session: **${session.name}**
Framework: **${framework}**
Generated: ${new Date().toISOString()}
Start URL: ${session.startUrl}

## How to run

${runCommand}

## Project structure

${structure}

## Self-healing locators

Each page-object element ships with a \`// Fallbacks: ...\` comment listing
the locator strategies PlayForge ranked just below the primary. When a UI
change breaks the primary selector, swap in a fallback or wire up the
included helper:

${selfHealingNote}

Generated by [PlayForge](https://github.com/your-username/playforge).
`
}

/** Classify a generated file into its ZIP folder. */
function resolveZipPath(filename: string, framework: string): string {
  // Already-namespaced paths (e.g. cypress/support/e2e.js) pass through as-is
  if (filename.includes('/')) return filename

  // Top-level config files are kept at root
  if (filename === 'package.json') return filename
  if (filename === 'playwright.config.ts') return filename
  if (filename === 'cypress.config.js') return filename
  if (filename === 'tsconfig.json') return filename

  if (framework === 'cypress') {
    if (filename.endsWith('.cy.js')) return `cypress/e2e/${filename}`
    if (filename.endsWith('.js')) return `cypress/pages/${filename}`
    return filename
  }

  // Playwright (default)
  if (filename.endsWith('.spec.ts')) return `tests/${filename}`
  if (filename.endsWith('.ts')) return `pages/${filename}`
  return filename
}

export async function buildZipExport(session: Session, code: GeneratedCode): Promise<Blob> {
  const zip = new JSZip()

  for (const file of code.files) {
    zip.file(resolveZipPath(file.filename, code.framework), file.content)
  }

  zip.file('README.md', README_TEMPLATE(session, code.framework))

  return zip.generateAsync({ type: 'blob', compression: 'DEFLATE' })
}

export async function downloadZipExport(session: Session, code: GeneratedCode): Promise<void> {
  const blob = await buildZipExport(session, code)
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${slugify(session.name)}_${session.sessionId.slice(0, 8)}.zip`
  a.click()
  URL.revokeObjectURL(url)
}

function slugify(name: string): string {
  return name.replace(/\s+/g, '_').replace(/[^\w-]/g, '')
}
