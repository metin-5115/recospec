/**
 * Self-healing locator scaffold — single source of truth.
 *
 * Exports both a testable TypeScript implementation (used by unit tests) and
 * the source strings that get emitted into the generated test project (so the
 * runtime helper inside the user's project doesn't depend on Recospec code).
 */

export interface MinimalPlaywrightPage {
  locator: (selector: string) => MinimalPlaywrightLocator
}

export interface MinimalPlaywrightLocator {
  count(): Promise<number>
}

/**
 * Try selectors in order and return the first one whose `.count()` is positive.
 * Mirrors the logic of the helper that ships in the generated Playwright zip.
 */
export async function selfHealingLocator(
  page: MinimalPlaywrightPage,
  selectors: string[],
): Promise<MinimalPlaywrightLocator> {
  if (selectors.length === 0) {
    throw new Error('selfHealingLocator: no selectors provided')
  }
  const tried: string[] = []
  for (const sel of selectors) {
    try {
      const loc = page.locator(sel)
      const matches = await loc.count()
      if (matches > 0) return loc
      tried.push(`${sel} (no match)`)
    } catch (err) {
      tried.push(`${sel} (${err instanceof Error ? err.message : String(err)})`)
    }
  }
  throw new Error(
    `selfHealingLocator: all ${selectors.length} selectors failed:\n${tried.join('\n')}`,
  )
}

/**
 * Source emitted as `utils/locator.ts` in the Playwright scaffold.
 * Kept verbatim — runtime behaviour matches `selfHealingLocator` above.
 */
export const PLAYWRIGHT_SELF_HEALING_TS = `import type { Locator, Page } from '@playwright/test';

/**
 * Try CSS / role / test-id selectors in order. Returns the first locator
 * whose count() resolves above zero. Pass the primary selector first, then
 * the recorded fallbacks — generated by Recospec.
 *
 * @example
 *   const email = await selfHealingLocator(page, [
 *     '[data-testid="email"]',
 *     '[aria-label="Email"]',
 *   ]);
 *   await email.fill('user@example.com');
 */
export async function selfHealingLocator(page: Page, selectors: string[]): Promise<Locator> {
  if (selectors.length === 0) {
    throw new Error('selfHealingLocator: no selectors provided');
  }
  const tried: string[] = [];
  for (const sel of selectors) {
    try {
      const loc = page.locator(sel);
      if ((await loc.count()) > 0) return loc;
      tried.push(\`\${sel} (no match)\`);
    } catch (err) {
      tried.push(\`\${sel} (\${err instanceof Error ? err.message : String(err)})\`);
    }
  }
  throw new Error(
    \`selfHealingLocator: all \${selectors.length} selectors failed:\\n\${tried.join('\\n')}\`,
  );
}
`

/**
 * Source emitted as `cypress/support/locator.js` in the Cypress scaffold.
 * Registers `cy.selfHealing(['#primary', '[data-testid="primary"]'])`.
 */
export const CYPRESS_SELF_HEALING_JS = `/**
 * cy.selfHealing(['#primary', '[data-testid="primary"]'])
 *
 * Yields the first selector whose query returns at least one element.
 * Pass the primary selector first, then the fallbacks recorded by Recospec.
 */
Cypress.Commands.add('selfHealing', (selectors) => {
  if (!Array.isArray(selectors) || selectors.length === 0) {
    throw new Error('cy.selfHealing: pass a non-empty array of selectors');
  }
  const tryAt = (idx) => {
    if (idx >= selectors.length) {
      throw new Error('cy.selfHealing: all selectors failed: ' + selectors.join(', '));
    }
    return cy.document({ log: false }).then((doc) => {
      if (doc.querySelector(selectors[idx])) {
        return cy.get(selectors[idx]);
      }
      return tryAt(idx + 1);
    });
  };
  return tryAt(0);
});
`
